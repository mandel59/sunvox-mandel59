function clamp(value, min, max) {
  return Math.min(max, Math.max(min, value));
}

function noteNameFromNumber(noteNumber) {
  if (!Number.isInteger(noteNumber) || noteNumber < 0 || noteNumber > 127) {
    throw new Error(`43EDO carrier note is outside SunVox range: ${noteNumber}`);
  }
  return `${NOTE_NAMES[noteNumber % 12]}${Math.floor(noteNumber / 12)}`;
}

function noteFromStep(step) {
  return noteNameFromNumber(ROOT_NOTE_NUMBER + step);
}

function pitchRemapCurve43Edo() {
  return Array.from({ length: 128 }, (_, noteNumber) =>
    clamp(Math.round(16384 + (ROOT_NOTE_NUMBER + ((noteNumber - ROOT_NOTE_NUMBER) * 12) / EDO_STEPS) * 256), 0, 65535),
  );
}

