function note(events, lines, { line, track, step, module, velocity = 112, gate = 4 }) {
  if (line < 0 || line >= lines) {
    return;
  }
  events.push({ line, track, note: noteFromStep(step), velocity, module });
  const offLine = line + gate;
  if (gate > 0 && offLine > line && offLine < lines) {
    events.push({ line: offLine, track, note: "noteOff", module });
  }
}

function chord(events, lines, { line, track, steps, module, velocity = 96, gate = 16 }) {
  steps.forEach((step, index) => {
    note(events, lines, { line, track: track + index, step, module, velocity, gate });
  });
}

function buildPrimeLatticeEvents(lines) {
  const events = [];
  const cells = [
    { root: -43, chord: [0, 14, 25, 35], bass: [-43, -18], lead: [0, 14, 25, 35, 25, 14, 10, 0] },
    { root: -33, chord: [0, 10, 25, 32], bass: [-33, -8], lead: [10, 25, 32, 45, 35, 25, 18, 10] },
    { root: -25, chord: [0, 14, 18, 43], bass: [-25, 0], lead: [18, 25, 32, 43, 57, 43, 35, 25] },
    { root: -18, chord: [0, 10, 25, 35], bass: [-18, 7], lead: [35, 32, 25, 18, 14, 10, 0, -8] },
  ];

  for (let bar = 0; bar < 8; bar += 1) {
    const line = bar * 16;
    const cell = cells[bar % cells.length];
    chord(events, lines, {
      line,
      track: TRACK.pad,
      steps: cell.chord.map((step) => cell.root + 43 + step),
      module: MODULE.padMap,
      velocity: 76 + (bar % 2) * 8,
      gate: 15,
    });
    for (let beat = 0; beat < 4; beat += 1) {
      note(events, lines, {
        line: line + beat * 4,
        track: TRACK.bass,
        step: cell.bass[beat % cell.bass.length],
        module: MODULE.bassMap,
        velocity: beat === 0 ? 124 : 98,
        gate: 3,
      });
    }
    cell.lead.forEach((step, index) => {
      note(events, lines, {
        line: line + index * 2,
        track: TRACK.lead + (index % 2),
        step: cell.root + 43 + step,
        module: MODULE.leadMap,
        velocity: 92 + (index % 3) * 10,
        gate: index % 4 === 3 ? 3 : 2,
      });
    });
    [14, 25, 35].forEach((step, index) => {
      note(events, lines, {
        line: line + 6 + index * 4,
        track: TRACK.accent + index,
        step: cell.root + 43 + step + (bar % 2 ? 10 : 0),
        module: MODULE.accentMap,
        velocity: 66,
        gate: 2,
      });
    });
  }

  return events.sort(compareEvents);
}

function buildNeutralTetrachordEvents(lines) {
  const events = [];
  const lower = [0, 5, 12, 18];
  const upper = [25, 30, 37, 43];
  const scale = [...lower, ...upper];
  const roots = [-43, -31, -25, -18, -13, -25, -31, -43, -36];
  const melody = [0, 5, 12, 18, 12, 5, 0, -1, 0, 12, 18, 25, 30, 25, 18, 12];

  for (let bar = 0; bar < 9; bar += 1) {
    const line = bar * 16;
    const root = roots[bar % roots.length];
    chord(events, lines, {
      line,
      track: TRACK.pad,
      steps: [0, 12, 25, 37].map((step) => root + 43 + step),
      module: MODULE.padMap,
      velocity: 72,
      gate: 15,
    });
    for (let beat = 0; beat < 4; beat += 1) {
      note(events, lines, {
        line: line + beat * 4,
        track: TRACK.bass,
        step: root + (beat === 3 ? 25 : 0),
        module: MODULE.bassMap,
        velocity: beat === 0 ? 122 : 88,
        gate: 3,
      });
    }
    melody.forEach((degree, index) => {
      const ornament = index % 8 === 7 ? -1 : 0;
      note(events, lines, {
        line: line + index,
        track: TRACK.lead + (index % 3),
        step: root + 43 + degree + ornament,
        module: MODULE.leadMap,
        velocity: 78 + ((index + bar) % 5) * 7,
        gate: index % 4 === 0 ? 2 : 1,
      });
    });
    scale.slice(1, 7).forEach((degree, index) => {
      if ((bar + index) % 3 === 0) {
        note(events, lines, {
          line: line + 2 + index * 2,
          track: TRACK.accent + index,
          step: root + 43 + degree,
          module: MODULE.accentMap,
          velocity: 86,
          gate: 2,
        });
      }
    });
  }

  return events.sort(compareEvents);
}

function buildMosFifthCanonEvents(lines) {
  const events = [];
  const mos = [0, 7, 14, 21, 25, 32, 39];
  const subject = [0, 25, 7, 32, 14, 39, 21, 43, 32, 25, 14, 7, 0];
  const roots = [-43, -29, -36, -25, -32, -22, -39, -43, -29, -36];

  for (let bar = 0; bar < 10; bar += 1) {
    const line = bar * 16;
    const root = roots[bar % roots.length];
    note(events, lines, {
      line,
      track: TRACK.bass,
      step: root,
      module: MODULE.bassMap,
      velocity: 118,
      gate: 7,
    });
    note(events, lines, {
      line: line + 8,
      track: TRACK.bass + 1,
      step: root + 25,
      module: MODULE.bassMap,
      velocity: 98,
      gate: 7,
    });
    chord(events, lines, {
      line,
      track: TRACK.pad,
      steps: [mos[0], mos[2], mos[4], mos[6]].map((step) => root + 43 + step),
      module: MODULE.padMap,
      velocity: 68,
      gate: 15,
    });

    for (let voice = 0; voice < 3; voice += 1) {
      subject.forEach((degree, index) => {
        const startLine = line + voice * 2 + index;
        if (startLine >= line + 16) {
          return;
        }
        note(events, lines, {
          line: startLine,
          track: TRACK.lead + voice,
          step: root + 43 + degree + voice * 7,
          module: MODULE.leadMap,
          velocity: 74 + voice * 8 + (index % 2) * 6,
          gate: 1,
        });
      });
    }

    [0, 7, 25, 32].forEach((degree, index) => {
      note(events, lines, {
        line: line + 3 + index * 3,
        track: TRACK.accent + index,
        step: root + 43 + degree + (bar % 2 ? 14 : 0),
        module: MODULE.accentMap,
        velocity: 62,
        gate: 1,
      });
    });
  }

  return events.sort(compareEvents);
}

function compareEvents(a, b) {
  return a.line - b.line || a.track - b.track || (a.module ?? 0) - (b.module ?? 0);
}

function applyDeterministicPatternIcons(document) {
  for (const [index, pattern] of (document.patterns ?? []).entries()) {
    pattern.iconBase64 = deterministicIconBase64(42 + index, index);
  }
}

