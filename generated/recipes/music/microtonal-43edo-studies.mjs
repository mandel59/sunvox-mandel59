export async function writeMicrotonal43EdoStudies(outputFiles = {}) {
  const written = [];
  for (const study of STUDIES) {
    const outputPath = resolve(outputFiles[study.id] ?? study.file);
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, buildContainer(buildDocument(study)));
    written.push(outputPath);
  }
  return written;
}

